/*
 * One-off font vendoring: downloads the latin woff2 subsets from Google
 * Fonts and generates src/client/styles/fonts.css with self-hosted
 * @font-face rules. Run `node scripts/fetch-fonts.mjs` once and commit the
 * results — at runtime the site never touches a third-party origin.
 */
import { mkdirSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const FONT_DIR = path.join(ROOT, 'public', 'fonts');
const UA =
  'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/126.0 Safari/537.36';

const FAMILIES = [
  {
    css: 'https://fonts.googleapis.com/css2?family=Fraunces:ital,opsz,wght@0,9..144,100..900;1,9..144,100..900&display=swap',
    name: 'Fraunces',
  },
  {
    css: 'https://fonts.googleapis.com/css2?family=IBM+Plex+Sans:wght@400;500;600;700&display=swap',
    name: 'IBM Plex Sans',
  },
  {
    css: 'https://fonts.googleapis.com/css2?family=IBM+Plex+Mono:wght@400;500;600&display=swap',
    name: 'IBM Plex Mono',
  },
];

mkdirSync(FONT_DIR, { recursive: true });

const faceBlocks = [];
let fileCount = 0;

for (const family of FAMILIES) {
  const res = await fetch(family.css, { headers: { 'User-Agent': UA } });
  if (!res.ok) throw new Error(`css fetch failed for ${family.name}: ${res.status}`);
  const css = await res.text();

  // Split into @font-face blocks; keep only the /* latin */ subset of each.
  const blocks = css.split('@font-face').slice(1);
  let prevComment = '';
  for (const chunk of css.split('\n')) {
    if (chunk.startsWith('/*')) prevComment = chunk;
  }
  for (const block of blocks) {
    const beforeIdx = css.indexOf('@font-face' + block);
    const before = css.slice(0, beforeIdx);
    const lastComment = before.slice(before.lastIndexOf('/*'));
    if (!lastComment.includes('latin') || lastComment.includes('latin-ext')) continue;

    const url = block.match(/url\((https:[^)]+\.woff2)\)/)?.[1];
    const style = block.match(/font-style:\s*(\w+)/)?.[1] ?? 'normal';
    const weight = block.match(/font-weight:\s*([\d\s]+);/)?.[1]?.trim() ?? '400';
    const unicodeRange = block.match(/unicode-range:\s*([^;]+);/)?.[1];
    if (!url) continue;

    const slug =
      family.name.toLowerCase().replace(/\s+/g, '-') +
      `-${style}-${weight.replace(/\s+/g, '-')}.woff2`;
    const fontRes = await fetch(url, { headers: { 'User-Agent': UA } });
    if (!fontRes.ok) throw new Error(`font fetch failed: ${url}`);
    writeFileSync(path.join(FONT_DIR, slug), Buffer.from(await fontRes.arrayBuffer()));
    fileCount += 1;

    faceBlocks.push(
      `@font-face {\n` +
        `  font-family: '${family.name}';\n` +
        `  font-style: ${style};\n` +
        `  font-weight: ${weight};\n` +
        (block.includes('font-optical-sizing') || family.name === 'Fraunces'
          ? `  font-optical-sizing: auto;\n`
          : '') +
        `  font-display: swap;\n` +
        `  src: url('/fonts/${slug}') format('woff2');\n` +
        (unicodeRange ? `  unicode-range: ${unicodeRange};\n` : '') +
        `}`,
    );
    console.log(`  ${slug}`);
  }
}

const header =
  `/* Self-hosted fonts (generated by scripts/fetch-fonts.mjs — do not edit\n` +
  ` * by hand; re-run the script to refresh). Latin subsets only. */\n\n`;
writeFileSync(path.join(ROOT, 'src', 'client', 'styles', 'fonts.css'), header + faceBlocks.join('\n\n') + '\n');
console.log(`[fonts] wrote ${fileCount} woff2 files + fonts.css`);
