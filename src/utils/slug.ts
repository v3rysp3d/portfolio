/**
 * Converts arbitrary text into a URL-safe slug:
 * lowercase, ASCII alphanumerics and single hyphens, no leading/trailing hyphen.
 */
export function slugify(input: string): string {
  return input
    .normalize('NFKD')
    .replace(/[̀-ͯ]/g, '') // strip diacritics
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '')
    .slice(0, 120);
}
